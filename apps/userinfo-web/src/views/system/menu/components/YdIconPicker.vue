/** 过滤后的图标列表 */
const filteredIcons = computed(() => {
  const keyword = searchKeyword.value.toLowerCase().trim();
  if (!keyword) return ICON_LIST;
  return ICON_LIST.filter(
    (icon) =>
      icon.name.toLowerCase().includes(keyword) || icon.label.toLowerCase().includes(keyword),
  );
});

/** 打开弹窗 */
function open(): void {
  visible.value = true;
  searchKeyword.value = '';
  selectedIcon.value = '';
}

/** 关闭弹窗 */
function close(): void {
  visible.value = false;
  emit('close');
}

/** 选择图标 */
function selectIcon(icon: { name: string; label: string }): void {
  selectedIcon.value = icon.name;
  emit('select', icon.name);
  showToast.success(`已选择图标：${icon.label}`);
  close();
}

/** 清除选择 */
function clearSelection(): void {
  selectedIcon.value = '';
  emit('select', '');
  close();
}

